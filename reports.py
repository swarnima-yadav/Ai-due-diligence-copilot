"""PDF export for the executive summary."""
import io
import re
from xml.sax.saxutils import escape
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

DISCLAIMER = ("This report was generated by an AI system from the documents supplied by the user. It may contain "
              "errors or omissions and is NOT certified investment, legal or financial advice. Verify all figures "
              "against the original documents before making decisions.")


def _p(text: str) -> str:
    t = escape(str(text)).replace("\n", "<br/>")
    return re.sub(r"(^|<br/>)\s*- ", r"\1&bull; ", t)


def build_pdf(company: str, created: str, report: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=18 * mm, bottomMargin=18 * mm, title=f"Executive Summary - {company}")
    ss = getSampleStyleSheet()
    h1, h2, body = ss["Title"], ss["Heading2"], ParagraphStyle("b", parent=ss["BodyText"], leading=14)
    small = ParagraphStyle("s", parent=body, fontSize=8.5, textColor="#555555")
    out = [Paragraph(_p(f"Executive Summary: {company}"), h1), Paragraph(_p(f"Generated: {created}"), small), Spacer(1, 6),
           Paragraph(_p("Disclaimer: " + DISCLAIMER), small), Spacer(1, 10)]
    for n, (title, text) in enumerate(report["sections"].items(), 1):
        out += [Paragraph(_p(f"{n}. {title}"), h2), Paragraph(_p(text), body), Spacer(1, 6)]
    out.append(Paragraph("9. Sources and references", h2))
    if report["sources"]:
        for s in report["sources"]:
            out.append(Paragraph(_p(f"[{s['label']}] {s['file']} ({s.get('doc_type', '')}), page {s['page']}"), body))
    else:
        out.append(Paragraph("No sources were cited.", body))
    doc.build(out)
    return buf.getvalue()
